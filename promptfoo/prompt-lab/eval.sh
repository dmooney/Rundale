#!/usr/bin/env bash
# Runs `promptfoo eval` for the lab, loading API keys from the repository's
# .env when it exists (keys already in the environment win). Pass promptfoo's
# eval arguments straight through; run it from anywhere.
#   bash promptfoo/prompt-lab/eval.sh -c promptfooconfig.yaml --no-cache -o output/round-01.json
#
# What it runs (2026-11-25, to make rounds cheap):
#   LAB_MODELS=flash-lite (default) runs only the production model;
#             LAB_MODELS=all runs every provider in the config (adds flash), for
#             the final check. An explicit --filter-providers wins.
#   LAB_JUDGES=opus (default) scores with the Opus judge only, for rounds;
#             LAB_JUDGES=both adds the GPT judge, for the control's comparison
#             and the held-out check. Scores are comparable only between runs
#             with the same judges.
# Estimated cost per training round (47 cases), from the per-reply costs
# measured in run 2's rounds 00 and 01 (flash-lite reply $0.001, flash $0.0045,
# Opus $0.040, GPT at xhigh $0.019; GPT at medium is not yet measured, guessed
# at about $0.012). These are estimates, not quotes:
#   flash-lite, Opus only (default)   about $1.95
#   flash-lite, both judges           about $2.50
#   both models, both judges          about $5.20
#
# Exits 3 when any reply is an outage (a failed request or judge, such as an
# exhausted credit balance), so a chained batch stops at the first void run
# instead of paying for the rest.
# Before calling anything it checks the OpenRouter balance and exits 4 when less
# than LAB_MIN_CREDIT_USD is left (default: $3 for the default round, $7 when
# LAB_MODELS=all or LAB_JUDGES=both, each about one such round plus margin), so a
# round is not voided halfway by "402 Payment Required".
# LAB_DRY_RUN=1 prints the promptfoo arguments it would use and exits, with no
# calls (check.sh uses it).
set -euo pipefail
cd "$(dirname "$0")"
export PROMPTFOO_DISABLE_TELEMETRY=1
# A judge at high reasoning effort can take over promptfoo's default 300 s per
# request; a timeout is an outage that voids the whole round.
export REQUEST_TIMEOUT_MS="${REQUEST_TIMEOUT_MS:-900000}"

models="${LAB_MODELS:-flash-lite}"
judges="${LAB_JUDGES:-opus}"
case "$models" in flash-lite | all) ;; *)
    echo "eval.sh: LAB_MODELS must be flash-lite or all" >&2
    exit 2
    ;;
esac
case "$judges" in opus | both) ;; *)
    echo "eval.sh: LAB_JUDGES must be opus or both" >&2
    exit 2
    ;;
esac
min_default=3
[ "$models" = all ] || [ "$judges" = both ] && min_default=7
min_credit="${LAB_MIN_CREDIT_USD:-$min_default}"

# Rewrite the arguments: note the output file, swap the config for an Opus-only
# copy when LAB_JUDGES=opus, and add the flash-lite filter unless one was given.
out=""
config="promptfooconfig.yaml"
has_config=0
has_provider_filter=0
args=()
prev=""
for a in "$@"; do
    case "$prev" in
        -o | --output) out=$a ;;
        -c | --config) config=$a ;;
    esac
    case "$a" in
        -c | --config) has_config=1 ;;
        --filter-providers | --filter-targets) has_provider_filter=1 ;;
    esac
    args+=("$a")
    prev=$a
done
if [ "$judges" = opus ]; then
    # The copy sits beside the config so its relative file:// paths still resolve.
    opus_config="$(dirname "$config")/.opus-only.$(basename "$config")"
    node -e '
      const yaml = require(require.resolve("js-yaml", { paths: ["../node_modules"] }));
      const fs = require("fs");
      const cfg = yaml.load(fs.readFileSync(process.argv[1], "utf8"));
      const before = cfg.defaultTest.assert.length;
      cfg.defaultTest.assert = cfg.defaultTest.assert.filter((a) => a.metric !== "gpt");
      if (cfg.defaultTest.assert.length !== before - 1) throw new Error("expected exactly one gpt judge in " + process.argv[1]);
      fs.writeFileSync(process.argv[2], "# Generated by eval.sh (LAB_JUDGES=opus); do not edit.\n" + yaml.dump(cfg));
    ' "$config" "$opus_config"
    if [ "$has_config" = 1 ]; then
        for i in "${!args[@]}"; do
            if [ "${args[$i]}" = "$config" ] && { [ "${args[$((i - 1))]:-}" = -c ] || [ "${args[$((i - 1))]:-}" = --config ]; }; then
                args[i]="$opus_config"
            fi
        done
    else
        args+=(-c "$opus_config")
    fi
fi
if [ "$models" = flash-lite ] && [ "$has_provider_filter" = 0 ]; then
    args+=(--filter-providers '^flash-lite$')
fi
echo "eval.sh: models=$models judges=$judges" >&2
if [ "${LAB_DRY_RUN:-}" = 1 ]; then
    # For check.sh: show the promptfoo arguments and stop before any call.
    printf '%s\n' "${args[@]}"
    exit 0
fi

env_args=()
[ -f ../../.env ] && env_args=(--env-file ../../.env)
key="${OPENROUTER_API_KEY:-}"
if [ -z "$key" ] && [ -f ../../.env ]; then
    key=$(sed -n 's/^OPENROUTER_API_KEY=//p' ../../.env | head -1 | tr -d "\"'")
fi
if [ -n "$key" ] && [ "${LAB_SKIP_CREDIT_CHECK:-}" != 1 ]; then
    left=$(curl -fsS --max-time 20 https://openrouter.ai/api/v1/credits -H "Authorization: Bearer $key" \
        | jq -r '.data.total_credits - .data.total_usage') || left=""
    if [ -z "$left" ]; then
        echo "eval.sh: could not read the OpenRouter balance; set LAB_SKIP_CREDIT_CHECK=1 to run anyway" >&2
        exit 4
    fi
    if jq -en --argjson l "$left" --argjson m "$min_credit" '$l < $m' >/dev/null; then
        printf 'eval.sh: only $%.2f of OpenRouter credit left (need $%s); add credit or lower LAB_MIN_CREDIT_USD\n' "$left" "$min_credit" >&2
        exit 4
    fi
fi

status=0
../node_modules/.bin/promptfoo eval "${env_args[@]}" "${args[@]}" || status=$?
if [ -n "$out" ] && [ -f "$out" ]; then
    outages=$(jq -f summary.jq "$out" | jq -r '[.prompts[].all_models.outages[]] | length, (group_by(.why) | map("  \(length)x \(.[0].why)") | .[])')
    if [ "$(head -1 <<<"$outages")" != "0" ]; then
        echo "eval.sh: $(head -1 <<<"$outages") outages; this run is void and must be rerun whole:" >&2
        tail -n +2 <<<"$outages" >&2
        exit 3
    fi
fi
# promptfoo exits 100 when any assertion fails, which is normal for a scored run.
[ "$status" = 0 ] || [ "$status" = 100 ] || exit "$status"
